import { chmod, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { build } from "esbuild";
const root = fileURLToPath(new URL("..", import.meta.url));
await rm(join(root, "dist"), { recursive: true, force: true });
const settings = { absWorkingDir: root, bundle: true, platform: "node", format: "esm", target: "node24", external: ["node-pty"], logLevel: "warning" };
await build({ ...settings, entryPoints: ["src/cli.ts"], outfile: "dist/cli.js", banner: { js: "#!/usr/bin/env node" } });
await build({ ...settings, entryPoints: ["src/index.ts"], outfile: "dist/index.js" });
await chmod(join(root, "dist/cli.js"), 0o755);
