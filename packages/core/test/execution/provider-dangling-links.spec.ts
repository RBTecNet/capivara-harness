import { afterEach, expect, it } from 'vitest';
import { lstat, mkdir, mkdtemp, readFile, readlink, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { sourceFiles, inputSnapshot } from '../../src/execution/files.js';
import { createTaskWorkspace } from '../../src/execution/isolation.js';
import { beginEnvironmentRecovery, commitEnvironmentRecovery } from '../../src/execution/recovery-scope.js';
import { prepareEnvironmentNode } from '../../src/execution/environment.js';
import { snapshotWorkspace, projectPath } from '../../src/runtime/files.js';
import { executeCommand } from '../../src/runtime/command.js';
import type { EnvironmentNode, ProductBrief } from '../../src/domain/types.js';

const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });

it.skipIf(process.platform === 'win32')('preserves optional broken provider links through cloning and publication without discovering installations as product or approving a missing consumed executable', async () => {
  const root = await mkdtemp(join(tmpdir(), 'capivara-provider-links-')), outside = await mkdtemp(join(tmpdir(), 'capivara-provider-external-')); roots.push(root, outside);
  const installation = '.capivara-tools', bin = `${installation}/bin`, missing = `${installation}/root/usr/bin/nm`;
  await mkdir(join(root, bin), { recursive: true }); await mkdir(join(root, installation, 'root/usr/bin'), { recursive: true });
  await writeFile(join(root, 'app.mjs'), 'console.log("APP");\n');
  const program = `#!${process.execPath}\nconsole.log('PROVIDER READY');\n`;
  await writeFile(join(root, bin, 'provider'), program, { mode: 0o755 });
  await symlink('provider', join(root, bin, 'provider-link'));
  await symlink('missing-nm-target', join(root, missing));
  const externalMissing = join(outside, 'absent-provider');
  await symlink(externalMissing, join(root, installation, 'root/usr/bin/external'));
  expect(await sourceFiles(root)).toEqual(['app.mjs']);
  expect(await sourceFiles(root, ['.'])).toEqual(['app.mjs']);
  expect([...await snapshotWorkspace(root)].map(([path]) => path)).toEqual(['app.mjs']);
  expect((await inputSnapshot(root, [missing]))[`link:${missing}`]).toBe('missing-target:missing-nm-target');
  expect((await snapshotWorkspace(root, [missing])).get(missing)).toBe('link:missing-nm-target:missing-target');
  await expect(projectPath(root, `${bin}/provider`, true)).rejects.toThrow(/controle/);
  const clone = await createTaskWorkspace(root, 'app', 'definition', ['app.mjs']);
  expect(await readlink(join(clone.directory, missing))).toBe('missing-nm-target');
  expect(await readlink(join(clone.directory, installation, 'root/usr/bin/external'))).toBe(externalMissing);
  expect((await executeCommand({ cwd: clone.directory, command: [join(clone.directory, bin, 'provider-link')] })).stdout).toContain('PROVIDER READY');
  const node: EnvironmentNode = { id: 'provider', name: 'Provider installation', kind: 'tool', identity: { capability: 'provider', kind: 'cli', provider: 'Selected provider' }, dependsOn: [], targets: [], reason: 'Run the selected provider.', check: { command: `${bin}/provider`, args: [] }, prepare: [] };
  const recovery = await beginEnvironmentRecovery(root, node);
  await writeFile(join(recovery.directory, bin, 'provider'), program.replace('PROVIDER READY', 'PROVIDER READY 2'), { mode: 0o755 });
  const publication = await commitEnvironmentRecovery(root, node, recovery);
  expect(publication.dependencyDirectories).toContain(installation);
  expect(await readlink(join(root, missing))).toBe('missing-nm-target');
  expect(await readlink(join(root, installation, 'root/usr/bin/external'))).toBe(externalMissing);
  expect(await lstat(join(root, bin, 'provider-link')).then(info => info.isSymbolicLink())).toBe(true);
  expect((await executeCommand({ cwd: root, command: [join(root, bin, 'provider-link')] })).stdout).toContain('PROVIDER READY 2');
  expect(await sourceFiles(root)).toEqual(['app.mjs']); expect(await readFile(join(root, 'app.mjs'), 'utf8')).toBe('console.log("APP");\n');
  const brief: ProductBrief = { schema: 'capivara/product/1', id: 'b', revision: 1, status: 'ready', name: 'APP', summary: 'Run the app', request: 'Run the app', modes: ['cli'], targets: ['portable'], requirements: [], constraints: [], decisions: [], gaps: [] };
  const absent = await prepareEnvironmentNode(root, { ...node, provides: { command: [join(root, missing)] }, check: { command: join(root, missing), args: [] } }, brief, executeCommand);
  expect(absent.ready).toBe(false); expect(absent.incidents.length).toBeGreaterThan(0);
  await rm(join(root, missing)); await symlink('a-different-missing-target', join(root, missing));
  expect((await inputSnapshot(root, [missing]))[`link:${missing}`]).toBe('missing-target:a-different-missing-target');
});
